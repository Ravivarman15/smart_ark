// The client NEVER calls AiSensy directly because:
//   1. AiSensy API does not allow cross-origin browser requests (CORS)
//   2. The API key must stay server-side (never in the JS bundle)
//
// All WhatsApp sends go through supabase.functions.invoke("send-whatsapp")
// which reads AISENSY_API_KEY from Supabase secrets and calls AiSensy
// server-to-server.
//
// REQUIRED AISENSY CAMPAIGNS  (create once in your AiSensy dashboard)
// All templates must be submitted to Meta under category = UTILITY.
// IMPORTANT: Meta rejects templates that start or end with a {{variable}}
//            — always wrap variables in static text.
// ────────────────────────────────────────────────────────────────────
// 1. Campaign name : ark_student_marks_report   (7 variables)
//    Template body : "Dear Parent,\n\nWe are pleased to share the latest
//                    academic result.\n\nStudent: {{1}}\nSubject: {{2}}\n
//                    Score: {{3}} / {{4}}\nPercentage: {{5}}%\nGrade: {{6}}\n\n
//                    Remarks:\n{{7}}\n\nThank you,\nARK Learning Arena"
//    Variables     : {{1}}=student  {{2}}=subject+exam  {{3}}=marks
//                    {{4}}=total    {{5}}=percentage   {{6}}=grade  {{7}}=remarks
//
// 2. Campaign name : ark_daily_report_summary   (2 variables)
//    Template body : "ARK Daily Report – {{1}}\n\n{{2}}\n\n
//                    – Auto-generated by ARK Learning Arena"
//    Variables     : {{1}}=date  {{2}}=report text (up to 1024 chars)
//
// 3. Campaign name : ark_fee_payment_reminder   (3 variables, optional)
//    Template body : "Dear Parent, {{1}}'s tuition fee of ₹{{2}} is due by
//                    {{3}}. Kindly arrange the payment at the centre or
//                    contact us for assistance."
//    Variables     : {{1}}=student name  {{2}}=amount  {{3}}=due date
